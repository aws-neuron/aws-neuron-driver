const struct neuron_platform_desc *nplatform_get_platform_desc(const struct neuron_platform_desc *table)
{
	const char *name;
	char buf[128];
	int i, n;

	if (narch_get_instance_type_name(buf, sizeof(buf))) {
		return NULL;
	}

	for (i = 0; table[i].instance_names != NULL; i++) {
		for (n = 0; table[i].instance_names[n] != NULL; n++) {
			name = table[i].instance_names[n];
			if (strncmp(buf, name, strlen(name)) == 0) {
				return &table[i];
			}
		}
	}

	return NULL;
}

